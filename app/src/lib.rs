/// The application icon (PNG, generated by `cargo run --bin make_icon`).
pub const ICON_PNG: &[u8] = include_bytes!("../assets/icon.png");

pub fn icon_data() -> Option<egui::IconData> {
    let img = image::load_from_memory(ICON_PNG).ok()?.to_rgba8();
    let (w, h) = img.dimensions();
    Some(egui::IconData { rgba: img.into_raw(), width: w, height: h })
}

/// The logo shown in the top bars, `size` points square (loaded once, from the 180 px icon).
pub fn logo(ctx: &egui::Context, size: f32) -> egui::Image<'static> {
    let id = egui::Id::new("biocartoon_logo");
    let tex = ctx.data_mut(|d| d.get_temp::<egui::TextureHandle>(id)).unwrap_or_else(|| {
        let img = image::load_from_memory(include_bytes!("../assets/apple-touch-icon.png")).expect("bundled logo").to_rgba8();
        let ci = egui::ColorImage::from_rgba_unmultiplied([img.width() as usize, img.height() as usize], img.as_raw());
        let tex = ctx.load_texture("biocartoon_logo", ci, egui::TextureOptions::LINEAR);
        ctx.data_mut(|d| d.insert_temp(id, tex.clone()));
        tex
    });
    egui::Image::new(&tex).fit_to_exact_size(egui::vec2(size, size))
}

/// The project's source code, linked from the About window.
pub const GITHUB_URL: &str = "https://github.com/josephrich98/biocartoon-app";
/// The desktop download page, served next to the web app (`app/download.html`).
pub const DOWNLOAD_PAGE: &str = "download.html";

/// The web build's "Download desktop app" button (nothing on the desktop).
pub fn download_app_button(ui: &mut egui::Ui) {
    use egui_phosphor::regular as ph;
    if cfg!(target_arch = "wasm32") {
        let text = egui::RichText::new(format!("{}  Download desktop app", ph::DOWNLOAD_SIMPLE)).color(theme::accent());
        let button = egui::Button::new(text).fill(theme::panel()).stroke(egui::Stroke::new(1.0, theme::accent())).corner_radius(8);
        if ui.add(button).on_hover_text("Get BioCartoon for macOS, Windows or Linux").clicked() {
            ui.ctx().open_url(egui::OpenUrl::new_tab(DOWNLOAD_PAGE));
        }
    }
}
